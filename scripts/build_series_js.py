"""Write series/sps_series.js for the interactive chart on index.html.

Reads data/panda_shocks_monthly.csv and defines one JavaScript object, window.SPS_SERIES, with the
month labels and, for each of the 24 hosts, its ISO2 code, full name and the monthly arrays
z_birth_nat, z_birth_reg, z_birth_count, z_birth_cap90, z_death, z_hard and A_panda (null where
missing). Loaded by a plain <script src> tag, so the page also works when opened from the file system.

Run from the repository root after any change to data/:  python scripts/build_series_js.py
"""
import json
import math
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "panda_shocks_monthly.csv")
OUT = os.path.join(ROOT, "series", "sps_series.js")
COLS = ["z_birth_nat", "z_birth_reg", "z_birth_count", "z_birth_cap90", "z_death", "z_hard", "A_panda"]
NAMES = {
    "AT": "Austria", "AU": "Australia", "BE": "Belgium", "CA": "Canada", "DE": "Germany",
    "DK": "Denmark", "ES": "Spain", "FI": "Finland", "FR": "France", "GB": "United Kingdom",
    "HK": "Hong Kong", "ID": "Indonesia", "JP": "Japan", "KR": "South Korea", "MO": "Macau",
    "MX": "Mexico", "MY": "Malaysia", "NL": "Netherlands", "QA": "Qatar", "RU": "Russia",
    "SG": "Singapore", "TH": "Thailand", "TW": "Taiwan", "US": "United States",
}


def clean(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return None
    v = round(float(v), 4)
    return int(v) if v == int(v) else v


df = pd.read_csv(SRC, dtype={"host": str, "month": str}).sort_values(["host", "month"])
months = sorted(df["month"].unique())
hosts = sorted(df["host"].unique(), key=lambda h: NAMES[h])
out = {"source": "data/panda_shocks_monthly.csv", "version": "1.0", "months": months, "hosts": []}
for h in hosts:
    g = df[df["host"] == h].set_index("month").reindex(months)
    rec = {"code": h, "name": NAMES[h]}
    for c in COLS:
        rec[c] = [clean(v) for v in g[c].tolist()]
    out["hosts"].append(rec)
    nz = sum(1 for v in rec["z_birth_nat"] if v)
    print("%s %-15s nonzero z_birth_nat: %d" % (h, NAMES[h], nz))

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* Generated by scripts/build_series_js.py from data/panda_shocks_monthly.csv. Do not edit. */\n")
    fh.write("window.SPS_SERIES = ")
    json.dump(out, fh, separators=(",", ":"), ensure_ascii=False)
    fh.write(";\n")
print("wrote", OUT, "%d KB" % round(os.path.getsize(OUT) / 1024))
